    <script>
    let currentUploadType = null;
    const teacherId = <?= (int)($teacher_id ?? 0) ?>;
    const uploadUrl = '<?= base_url("admin/administrasi-guru/modul-ajar/upload-signature") ?>';
    const csrfName  = '<?= csrf_token() ?>';
    let csrfHash    = '<?= csrf_hash() ?>';

    // Inisialisasi status tanda tangan dari localStorage jika pernah disimpan
    document.addEventListener('DOMContentLoaded', function () {
        const savedKepsek = localStorage.getItem('modul_ajar_ttd_kepsek');
        const savedGuru   = localStorage.getItem('modul_ajar_ttd_guru');

        if (savedKepsek !== null) {
            const isChecked = savedKepsek === '1';
            const chk = document.getElementById('chk_ttd_kepsek');
            const img = document.getElementById('img_ttd_kepsek');
            if (img.getAttribute('src')) {
                chk.checked = isChecked;
                if (!isChecked) img.classList.add('d-none');
                else img.classList.remove('d-none');
            }
        }

        if (savedGuru !== null) {
            const isChecked = savedGuru === '1';
            const chk = document.getElementById('chk_ttd_guru');
            const img = document.getElementById('img_ttd_guru');
            if (img.getAttribute('src')) {
                chk.checked = isChecked;
                if (!isChecked) img.classList.add('d-none');
                else img.classList.remove('d-none');
            }
        }
    });

    function toggleSignature(type, show) {
        const img = document.getElementById(type === 'kepsek' ? 'img_ttd_kepsek' : 'img_ttd_guru');
        if (!img) return;

        if (show) {
            if (!img.getAttribute('src')) {
                alert('Tanda tangan scan ' + (type === 'kepsek' ? 'Kepala Sekolah' : 'Guru') + ' belum diunggah. Silakan klik tombol "Upload TTD".');
                document.getElementById(type === 'kepsek' ? 'chk_ttd_kepsek' : 'chk_ttd_guru').checked = false;
                return;
            }
            img.classList.remove('d-none');
        } else {
            img.classList.add('d-none');
        }

        localStorage.setItem('modul_ajar_ttd_' + type, show ? '1' : '0');
    }

    function triggerUpload(type) {
        currentUploadType = type;
        const fileInput = document.getElementById('input_sig_file');
        fileInput.value = '';
        fileInput.click();
    }

    function handleFileSelected(input) {
        if (!input.files || !input.files[0]) return;
        const file = input.files[0];

        if (file.size > 2 * 1024 * 1024) {
            alert('Ukuran file maksimal 2 MB.');
            return;
        }

        const formData = new FormData();
        formData.append('type', currentUploadType);
        formData.append('teacher_id', teacherId);
        formData.append('signature_file', file);
        formData.append(csrfName, csrfHash);

        const targetBadge = document.getElementById(currentUploadType === 'principal' ? 'badge_kepsek' : 'badge_guru');
        const prevBadgeText = targetBadge.textContent;
        targetBadge.textContent = 'Mengunggah...';

        fetch(uploadUrl, {
            method: 'POST',
            body: formData,
            headers: {
                'X-Requested-With': 'XMLHttpRequest'
            }
        })
        .then(async res => {
            const data = await res.json();
            return data;
        })
        .then(data => {
            if (data.success && data.base64) {
                if (currentUploadType === 'principal') {
                    const img = document.getElementById('img_ttd_kepsek');
                    img.src = data.base64;
                    img.classList.remove('d-none');
                    document.getElementById('chk_ttd_kepsek').checked = true;
                    targetBadge.className = 'sig-badge badge-success';
                    targetBadge.textContent = 'Scan Tersedia';
                    localStorage.setItem('modul_ajar_ttd_kepsek', '1');
                } else {
                    const img = document.getElementById('img_ttd_guru');
                    img.src = data.base64;
                    img.classList.remove('d-none');
                    document.getElementById('chk_ttd_guru').checked = true;
                    targetBadge.className = 'sig-badge badge-success';
                    targetBadge.textContent = 'Scan Tersedia';
                    localStorage.setItem('modul_ajar_ttd_guru', '1');
                }
                alert(data.message || 'Tanda tangan berhasil diperbarui!');
            } else {
                targetBadge.textContent = prevBadgeText;
                alert(data.message || 'Gagal mengunggah tanda tangan.');
            }
        })
        .catch(err => {
            targetBadge.textContent = prevBadgeText;
            alert('Terjadi kesalahan saat mengunggah: ' + err.message);
        });
    }

    function updateTitimangsaDate(val) {
        if (!val) return;
        const months = [
            'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni',
            'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'
        ];
        const parts = val.split('-');
        if (parts.length === 3) {
            const d = parseInt(parts[2], 10);
            const m = months[parseInt(parts[1], 10) - 1] || '';
            const y = parts[0];
            const formatted = d + ' ' + m + ' ' + y;
            document.getElementById('doc_titimangsa_date').textContent = formatted;
        }
    }
